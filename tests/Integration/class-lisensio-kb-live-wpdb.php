<?php
/**
 * A minimal mysqli-backed stand-in for $wpdb.
 *
 * Just enough surface for the installer and the feedback store to run their
 * real code against a real server. Without this the integration suite would
 * only prove things about MySQL; with it, the plugin's own
 * `detect_fulltext_index()`, `add_fulltext_index()` and every read and write
 * in Lisensio_KB_Feedback are the code under test.
 *
 * `prepare()` follows wpdb's own rules rather than approximating them, because
 * the vendored query builder depends on the difference: a bare `%s` is escaped
 * AND quoted, while a width-qualified `%1s` is escaped and left unquoted so it
 * can carry an operator or a column name. Getting that wrong produces SQL that
 * is syntactically valid and semantically wrong, which is precisely the kind of
 * defect this suite exists to catch.
 *
 * @package Lisensio_KB
 * @since   1.0.0
 */

/*
 * This suite connects to a real database on purpose: it exists precisely because
 * the unit suite's doubles cannot answer how a real server responds to real DDL.
 * The WordPress Database API is therefore not available or appropriate here.
 */
// phpcs:disable WordPress.DB.RestrictedClasses, WordPress.DB.RestrictedFunctions, WordPress.DB.DirectDatabaseQuery


/**
 * Routes the handful of $wpdb calls the installer makes at a live connection.
 *
 * @since 1.0.0
 */
class Lisensio_KB_Live_WPDB {

    /**
     * The live connection.
     *
     * @since 1.0.0
     * @var mysqli
     */
    private $db;

    /**
     * The last error reported by the server.
     *
     * @since 1.0.0
     * @var string
     */
    public $last_error = '';

    /**
     * Table prefix.
     *
     * @since 1.0.0
     * @var string
     */
    public $prefix = '';

    /**
     * The users table name, read by the query builder's prefixer.
     *
     * @since 1.0.0
     * @var string
     */
    public $users = '';

    /**
     * The user meta table name, read by the query builder's prefixer.
     *
     * @since 1.0.0
     * @var string
     */
    public $usermeta = '';

    /**
     * The ID generated by the last INSERT.
     *
     * @since 1.0.0
     * @var int
     */
    public $insert_id = 0;

    /**
     * The last statement sent to the server.
     *
     * @since 1.0.0
     * @var string
     */
    public $last_query = '';

    /**
     * Build the adapter.
     *
     * @since 1.0.0
     *
     * @param mysqli $db     A live connection.
     * @param string $prefix The table prefix in use.
     */
    public function __construct( $db, $prefix ) {
        $this->db       = $db;
        $this->prefix   = $prefix;
        $this->users    = $prefix . 'users';
        $this->usermeta = $prefix . 'usermeta';
    }

    /**
     * Run a statement.
     *
     * @since 1.0.0
     *
     * @param string $query The SQL statement.
     *
     * @return int|false Rows affected, or false on failure.
     */
    public function query( $query ) {
        $this->last_query = (string) $query;

        $result = $this->db->query( $query );

        $this->last_error = $this->db->error;

        if ( false === $result ) {
            return false;
        }

        $this->insert_id = (int) $this->db->insert_id;

        return $this->db->affected_rows < 0 ? 1 : (int) $this->db->affected_rows;
    }

    /**
     * Insert one row.
     *
     * @since 1.0.0
     *
     * @param string               $table  The table.
     * @param array<string, mixed> $data   Column to value.
     * @param array<int, string>   $format Ignored; every value is escaped as a string.
     *
     * @return int|false Rows inserted, or false on failure.
     */
    public function insert( $table, $data, $format = null ) {
        unset( $format );

        $columns = array();
        $values  = array();

        foreach ( (array) $data as $column => $value ) {
            $columns[] = '`' . str_replace( '`', '', (string) $column ) . '`';
            $values[]  = "'" . $this->db->real_escape_string( (string) $value ) . "'";
        }

        return $this->query(
            'INSERT INTO ' . $table . ' (' . implode( ', ', $columns ) . ') VALUES (' . implode( ', ', $values ) . ')'
        );
    }

    /**
     * Update the rows matching a set of equality conditions.
     *
     * @since 1.0.0
     *
     * @param string               $table        The table.
     * @param array<string, mixed> $data         Column to new value.
     * @param array<string, mixed> $where        Column to matched value.
     * @param array<int, string>   $format       Ignored.
     * @param array<int, string>   $where_format Ignored.
     *
     * @return int|false Rows updated, or false on failure.
     */
    public function update( $table, $data, $where, $format = null, $where_format = null ) {
        unset( $format, $where_format );

        $sets = array();

        foreach ( (array) $data as $column => $value ) {
            $sets[] = '`' . str_replace( '`', '', (string) $column ) . "` = '" . $this->db->real_escape_string( (string) $value ) . "'";
        }

        $conditions = array();

        foreach ( (array) $where as $column => $value ) {
            $conditions[] = '`' . str_replace( '`', '', (string) $column ) . "` = '" . $this->db->real_escape_string( (string) $value ) . "'";
        }

        $sql = 'UPDATE ' . $table . ' SET ' . implode( ', ', $sets );

        if ( ! empty( $conditions ) ) {
            $sql .= ' WHERE ' . implode( ' AND ', $conditions );
        }

        return $this->query( $sql );
    }

    /**
     * Run a statement and return its first row.
     *
     * @since 1.0.0
     *
     * @param string $query  The SQL statement.
     * @param string $output Ignored; rows are always returned as objects.
     *
     * @return object|null The first row, or null when there is none.
     */
    public function get_row( $query = '', $output = null ) {
        unset( $output );

        $rows = $this->get_results( $query );

        return isset( $rows[0] ) ? $rows[0] : null;
    }

    /**
     * Run a statement and return its rows as objects.
     *
     * @since 1.0.0
     *
     * @param string $query  The SQL statement.
     * @param string $output Ignored; rows are always returned as objects.
     *
     * @return array<int, object> The result rows.
     */
    public function get_results( $query, $output = null ) {
        unset( $output );

        $this->last_query = (string) $query;

        $result = $this->db->query( $query );

        $this->last_error = $this->db->error;

        if ( ! $result instanceof mysqli_result ) {
            return array();
        }

        $rows = array();

        while ( $row = $result->fetch_object() ) {
            $rows[] = $row;
        }

        return $rows;
    }

    /**
     * Interpolate a statement the way wpdb::prepare() does.
     *
     * A bare `%s` is escaped and quoted. A width-qualified placeholder such as
     * `%1s` is escaped and left unquoted, which is how the query builder passes
     * operators and column names. `%d` and `%f` are cast. `%%` collapses to a
     * literal per cent.
     *
     * @since 1.0.0
     *
     * @param string $query   The SQL statement.
     * @param mixed  ...$args Values to bind.
     *
     * @return string The prepared statement.
     */
    public function prepare( $query, ...$args ) {
        if ( 1 === count( $args ) && is_array( $args[0] ) ) {
            $args = $args[0];
        }

        $index = 0;
        $db    = $this->db;

        $prepared = preg_replace_callback(
            "/%%|%([-+0-9]*(?: |0|'.)?[-+0-9]*(?:\\.[0-9]+)?)?([sdfF])/",
            static function ( $matches ) use ( &$index, $args, $db ) {
                if ( '%%' === $matches[0] ) {
                    return '%';
                }

                $format = isset( $matches[1] ) ? $matches[1] : '';
                $type   = $matches[2];
                $value  = array_key_exists( $index, $args ) ? $args[ $index ] : '';

                ++$index;

                if ( 'd' === $type ) {
                    return (string) (int) $value;
                }

                if ( 'f' === $type || 'F' === $type ) {
                    return (string) (float) $value;
                }

                $escaped = $db->real_escape_string( (string) $value );

                return '' === $format ? "'" . $escaped . "'" : $escaped;
            },
            (string) $query
        );

        return (string) $prepared;
    }

    /**
     * Stop printing errors. The adapter never prints, so this is a no-op.
     *
     * @since 1.0.0
     *
     * @return bool Always false.
     */
    public function hide_errors() {
        return false;
    }

    /**
     * Start printing errors. The adapter never prints, so this is a no-op.
     *
     * @since 1.0.0
     *
     * @return bool Always true.
     */
    public function show_errors() {
        return true;
    }

    /**
     * The charset and collation clause.
     *
     * @since 1.0.0
     *
     * @return string The clause used in CREATE TABLE statements.
     */
    public function get_charset_collate() {
        return 'DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci';
    }

    /**
     * Toggle error suppression. The adapter never prints, so this is a no-op.
     *
     * @since 1.0.0
     *
     * @param bool $suppress Whether to suppress.
     *
     * @return bool The previous setting, always false.
     */
    public function suppress_errors( $suppress = true ) {
        unset( $suppress );

        return false;
    }
}
